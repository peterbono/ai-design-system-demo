#!/usr/bin/env node
// The Figma fix engine for Bridge's server: the parts of @bridge-ds/core that api/claude runs (the fix loop rounds,
// the values referee, the change for review, the GitHub client), bundled into one plain ES module,
// apps/docs-site/api/_lib/fix-engine.gen.js. The /api functions run as plain Node modules on Vercel and load no
// workspace package at runtime (core's sources import without extensions, and its dist is not built for the site), so
// the server runs this bundle of core's own code instead of a copy of it: nothing is forked.
//
//   node scripts/build-fix-engine.mjs           write the bundle (run it after changing what it exports or core)
//   node scripts/build-fix-engine.mjs --check   exit 1 when the committed bundle is not what core builds today
//
// apps/docs-site/src/lib/fix-engine-fresh.test.ts runs the check in CI, so the server never drifts from core.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const ENGINE_FILE = join(ROOT, 'apps/docs-site/api/_lib/fix-engine.gen.js');

/** What the server uses from core. Keep apps/docs-site/api/_lib/fix-engine.gen.d.ts in step (typecheck fails otherwise). */
export const ENGINE_EXPORTS = [
  'anthropicReplyText',
  'anthropicRequest',
  'DEFAULT_FIDELITY_RUN_FILE',
  'DEFAULT_FIGMA_FIXES_FILE',
  'DEFAULT_GOVERNANCE',
  'DEFAULT_MEASURED_SPECS_FILE',
  'FIX_LOOP_MAX_ROUNDS',
  'FIX_LOOP_MODEL',
  'figmaFixesProposal',
  'fixLoopOutcome',
  'fixLoopRound',
  'gapCaseFor',
  'GitHubClient',
  'loadConfig',
  'parseFidelityRun',
  'parseFigmaFixes',
  'parseMeasuredSpecsFile',
  'REQUESTS_BRANCH',
  'startFixLoop',
];

const HEADER = '// GENERATED by scripts/build-fix-engine.mjs from @bridge-ds/core. Do not edit: change core, then run the script.\n// eslint-disable';

export async function buildFixEngine() {
  const r = await esbuild.build({
    stdin: { contents: `export { ${ENGINE_EXPORTS.join(', ')} } from '@bridge-ds/core';\n`, resolveDir: ROOT, sourcefile: 'fix-engine-entry.ts', loader: 'ts' },
    absWorkingDir: ROOT,
    bundle: true,
    write: false,
    format: 'esm',
    platform: 'neutral',
    target: 'node20',
    conditions: ['source'],
    mainFields: ['module', 'main'],
    legalComments: 'none',
    charset: 'utf8',
    logLevel: 'silent',
    banner: { js: HEADER },
  });
  return r.outputFiles[0].text;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = await buildFixEngine();
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(ENGINE_FILE, 'utf8');
    } catch {
      /* missing: stale */
    }
    if (current !== text) {
      console.error('build-fix-engine: apps/docs-site/api/_lib/fix-engine.gen.js is stale. Run node scripts/build-fix-engine.mjs and commit it.');
      process.exit(1);
    }
    console.log('build-fix-engine: up to date.');
  } else {
    writeFileSync(ENGINE_FILE, text);
    console.log(`build-fix-engine: wrote ${ENGINE_FILE.slice(ROOT.length + 1)} (${Math.round(text.length / 1024)} KB).`);
  }
}
