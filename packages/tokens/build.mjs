// Builds DTCG 2025.10 tokens into dist/tokens.css (theme-scoped CSS variables) and dist/tokens.ts.
// Style Dictionary 4 reads DTCG ($value / $type) natively; the transforms below handle the
// 2025.10 object values (color objects, dimension objects, composite shadows).
import StyleDictionary from 'style-dictionary';
import { mkdir, writeFile } from 'node:fs/promises';

const valueOf = (token) => token.$value ?? token.value;
const typeOf = (token) => token.$type ?? token.type;

const toHex2 = (n) => Math.round(n * 255).toString(16).padStart(2, '0');

function colorToCss(c) {
  if (typeof c === 'string') return c;
  const [r, g, b] = c.components;
  const alpha = c.alpha ?? 1;
  if (alpha < 1) {
    return `rgb(${[r, g, b].map((x) => Math.round(x * 255)).join(' ')} / ${alpha})`;
  }
  return c.hex ?? `#${[r, g, b].map(toHex2).join('')}`;
}

const dimensionToCss = (d) => (typeof d === 'object' ? `${d.value}${d.unit}` : String(d));

function shadowToCss(s) {
  if (typeof s === 'string') return s;
  const layers = Array.isArray(s) ? s : [s];
  return layers
    .map((l) =>
      [l.inset ? 'inset' : '', dimensionToCss(l.offsetX), dimensionToCss(l.offsetY), dimensionToCss(l.blur), dimensionToCss(l.spread), colorToCss(l.color)]
        .filter(Boolean)
        .join(' '),
    )
    .join(', ');
}

const fontFamilyToCss = (f) =>
  Array.isArray(f) ? f.map((name) => (/\s/.test(name) ? `"${name}"` : name)).join(', ') : f;

StyleDictionary.registerTransform({
  name: 'dtcg/color',
  type: 'value',
  transitive: true,
  filter: (t) => typeOf(t) === 'color' && typeof valueOf(t) === 'object',
  transform: (t) => colorToCss(valueOf(t)),
});
StyleDictionary.registerTransform({
  name: 'dtcg/dimension',
  type: 'value',
  transitive: true,
  filter: (t) => typeOf(t) === 'dimension' && typeof valueOf(t) === 'object',
  transform: (t) => dimensionToCss(valueOf(t)),
});
StyleDictionary.registerTransform({
  name: 'dtcg/shadow',
  type: 'value',
  transitive: true,
  filter: (t) => typeOf(t) === 'shadow' && typeof valueOf(t) === 'object',
  transform: (t) => shadowToCss(valueOf(t)),
});
StyleDictionary.registerTransform({
  name: 'dtcg/font-family',
  type: 'value',
  filter: (t) => typeOf(t) === 'fontFamily',
  transform: (t) => fontFamilyToCss(valueOf(t)),
});
StyleDictionary.registerTransformGroup({
  name: 'demo/css',
  transforms: ['attribute/cti', 'name/kebab', 'dtcg/color', 'dtcg/dimension', 'dtcg/shadow', 'dtcg/font-family'],
});

// Typed map of every semantic token to its CSS variable, plus resolved primitive values.
StyleDictionary.registerFormat({
  name: 'demo/typescript',
  format: ({ dictionary }) => {
    const primitives = dictionary.allTokens.filter((t) => !t.isSource);
    const semantic = dictionary.allTokens.filter((t) => t.isSource);
    const line = (k, v) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`;
    return [
      '// Generated by packages/tokens/build.mjs. Do not edit by hand.',
      '',
      '/** Semantic tokens as CSS variable references. Theme-aware: values switch with [data-theme]. */',
      'export const cssVar = {',
      ...semantic.map((t) => line(t.name, `var(--${t.name})`)),
      '} as const;',
      '',
      '/** Resolved primitive values. Prefer cssVar in components; primitives are for tooling and docs. */',
      'export const primitives = {',
      ...primitives.map((t) => line(t.name, valueOf(t))),
      '} as const;',
      '',
      'export type SemanticToken = keyof typeof cssVar;',
      'export type PrimitiveToken = keyof typeof primitives;',
      '',
    ].join('\n');
  },
});

const PRIMITIVES = 'src/primitives/**/*.tokens.json';

async function render({ include = [], source, selector, ts = false }) {
  const sd = new StyleDictionary({
    usesDtcg: true,
    include,
    source,
    log: { verbosity: 'silent', warnings: 'disabled' },
    platforms: {
      css: {
        transformGroup: 'demo/css',
        files: [
          {
            destination: 'tokens.css',
            format: 'css/variables',
            filter: (t) => t.isSource,
            options: { selector, outputReferences: true, showFileHeader: false },
          },
        ],
      },
      ...(ts && {
        ts: { transformGroup: 'demo/css', files: [{ destination: 'tokens.ts', format: 'demo/typescript' }] },
      }),
    },
  });
  const css = (await sd.formatPlatform('css'))[0].output;
  const tsOut = ts ? (await sd.formatPlatform('ts'))[0].output : null;
  return { css, ts: tsOut };
}

const primitives = await render({ source: [PRIMITIVES], selector: ':root' });
const light = await render({ include: [PRIMITIVES], source: ['src/semantic/light.tokens.json'], selector: ':root,\n[data-theme="light"]', ts: true });
const dark = await render({ include: [PRIMITIVES], source: ['src/semantic/dark.tokens.json'], selector: '[data-theme="dark"]' });

const header = '/* Generated by packages/tokens/build.mjs from DTCG sources in src/. Do not edit by hand. */\n\n';
await mkdir('dist', { recursive: true });
await writeFile('dist/tokens.css', header + ['/* Primitives */', primitives.css, '/* Semantic: light (default) */', light.css, '/* Semantic: dark */', dark.css + '[data-theme="dark"] {\n  color-scheme: dark;\n}\n'].join('\n'));
await writeFile('dist/tokens.ts', light.ts);
console.log('tokens: wrote dist/tokens.css and dist/tokens.ts');
